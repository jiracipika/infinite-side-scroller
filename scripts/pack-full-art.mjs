#!/usr/bin/env node
// Pack the audited transparent figures directly. No segmentation, component
// deletion, trimming or rig refitting: the checked-in PNGs are the source of truth.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = process.cwd(), directory = path.join(root, 'design/full-art');
const ids = readdirSync(directory).filter(f => f.endsWith('.png') && f !== 'preview.png').map(f => f.slice(0, -4)).sort();
const entries = [], composites = [], cell = 220;
for (const [i, id] of ids.entries()) {
  const file = path.join(directory, `${id}.png`);
  const encoded = await sharp(file).resize({ width: 192, height: 192, fit: 'inside', kernel: 'lanczos3' })
    .webp({ quality: 92, alphaQuality: 100 }).toBuffer();
  entries.push(`  ${JSON.stringify(id)}: 'data:image/webp;base64,${encoded.toString('base64')}',`);
  const thumb = await sharp(file).resize({ width: 204, height: 190, fit: 'inside' }).png().toBuffer({ resolveWithObject: true });
  composites.push({ input: thumb.data, left: (i % 4) * cell + Math.round((cell - thumb.info.width) / 2), top: Math.floor(i / 4) * cell + 22 });
  composites.push({ input: Buffer.from(`<svg width="220" height="20"><text x="110" y="14" fill="#f4f2ed" font-family="monospace" font-size="13" text-anchor="middle">${id}</text></svg>`), left: i % 4 * cell, top: Math.floor(i / 4) * cell });
}
writeFileSync(path.join(root, 'src/game/rendering/character-fullart-data.ts'), `// GENERATED by scripts/pack-full-art.mjs — do not edit by hand.
// Source of truth: design/full-art/<id>.png. Pack directly after art changes;
// do not re-segment or scrub the audited figures. Maximum texture edge: 192px.
export const CHARACTER_FULL_ART: Record<string, string> = {
${entries.join('\n')}
};
`);
await sharp({ create: { width: 880, height: Math.ceil(ids.length / 4) * cell, channels: 4, background: '#21182b' } })
  .composite(composites).png().toFile(path.join(directory, 'preview.png'));
console.log(`Packed ${ids.length} complete character figures.`);
