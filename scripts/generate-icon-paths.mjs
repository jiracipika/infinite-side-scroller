#!/usr/bin/env node
// Builds src/components/icon-paths.ts from Lucide's icon data.
//
// The game ships one drawn stroke family instead of system emoji, which
// differ per OS and fall outside the black-ink palette. Nothing from the
// lucide-react package reaches the bundle: only path data is copied, under
// Lucide's ISC licence (the licence text is embedded from the package's own
// LICENSE file). Hand-drawn marks for what Lucide lacks live in Icon.tsx
// (INK_PATHS), not here.
//
//   node scripts/generate-icon-paths.mjs <lucide-react-package-dir> > src/components/icon-paths.ts
//
// Visual check — every icon at its real sizes on the ink palette:
//
//   node scripts/generate-icon-paths.mjs <lucide-react-package-dir> --sheet /tmp/icons.html
//
// Extra arguments replace the default name list (Lucide's kebab-case file
// names), which is how to audition candidates before adding one.

import fs from 'node:fs';
import path from 'node:path';

/** Every Lucide glyph the interface draws. Keep this list equal to what the
 *  screens use: the table is one object, so an unused entry is dead bytes. */
export const ICON_NAMES = [
  'arrow-left', 'arrow-right', 'arrow-up-right',
  'bot',
  'castle', 'check', 'circle-help', 'coins', 'compass', 'crosshair', 'crown',
  'flame', 'footprints',
  'gamepad-2', 'gem', 'globe', 'grid-2x2',
  'hand-heart', 'heart', 'heart-pulse',
  'infinity', 'link', 'list', 'lock',
  'magnet', 'map', 'medal', 'moon', 'move-horizontal',
  'party-popper', 'piggy-bank', 'plane-takeoff', 'play',
  'rainbow', 'rotate-ccw',
  'settings', 'shell', 'shield', 'shield-check', 'skull', 'snowflake', 'sparkle', 'sparkles',
  'star', 'sun', 'sunrise', 'sunset', 'sword', 'swords',
  'target', 'timer', 'trees', 'triangle-alert', 'trophy',
  'zap',
];

/** Parse one `dist/esm/icons/<name>.js` file into `[tag, attrs]` nodes. */
export function readIcon(packageDir, name) {
  const file = path.join(packageDir, 'dist', 'esm', 'icons', `${name}.js`);
  if (!fs.existsSync(file)) throw new Error(`lucide-react has no icon '${name}'`);
  const src = fs.readFileSync(file, 'utf8');
  const version = src.match(/@license lucide-react v([\d.]+)/)?.[1] ?? 'unknown';
  // Single-node icons are laid out on one line, the rest across several.
  const body = src.match(/createLucideIcon\("[^"]+", \[([\s\S]*?)\]\);/)?.[1];
  if (!body) throw new Error(`unexpected icon file layout: ${file}`);

  const nodes = [];
  // Long icons are printed one node per line with the attributes spread out.
  const nodePattern = /\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g;
  let match;
  while ((match = nodePattern.exec(body))) {
    const attrs = {};
    for (const part of match[2].split(/,\s*(?=\w+:)/)) {
      const pair = part.trim().match(/^(\w+):\s*(.*)$/s);
      if (!pair) continue;
      // React element keys are render-time detail; the table numbers its nodes.
      if (pair[1] === 'key') continue;
      const raw = pair[2].trim();
      attrs[pair[1]] = raw.startsWith('"') ? JSON.parse(raw) : raw;
    }
    if (!Object.keys(attrs).length) throw new Error(`node without geometry in ${file}`);
    nodes.push([match[1], attrs]);
  }
  // Every node carries exactly one React key, so counting keys proves that
  // the pattern above found the whole icon and not just its leading nodes.
  const expected = (body.match(/\bkey:/g) || []).length;
  if (!nodes.length || nodes.length !== expected) {
    throw new Error(`parsed ${nodes.length} of ${expected} nodes in ${file}`);
  }
  return { name, version, nodes };
}

function tsModule(packageDir, icons) {
  const licence = fs.readFileSync(path.join(packageDir, 'LICENSE'), 'utf8').trim();
  const version = icons[0].version;
  if (icons.some((icon) => icon.version !== version)) throw new Error('mixed lucide-react versions');
  const literal = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const rows = icons.map(({ name, nodes }) => {
    const parts = nodes.map(([tag, attrs]) =>
      `['${tag}', { ${Object.entries(attrs).map(([key, value]) => `${key}: ${literal(value)}`).join(', ')} }]`);
    return `  '${name}': [${parts.join(', ')}],`;
  });
  return `// Generated by scripts/generate-icon-paths.mjs from lucide-react v${version} — do not edit.
//
// Lucide (https://lucide.dev)
${licence.split('\n').map((line) => `// ${line}`.trimEnd()).join('\n')}

/** [svg tag, attributes] nodes on Lucide's 24×24 grid, drawn by <Icon>. */
export const LUCIDE_PATHS = {
${rows.join('\n')}
} as const;
`;
}

function sheet(packageDir, icons) {
  const draw = (icon, size, fill = 'none') =>
    `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="${fill}" stroke="currentColor" stroke-width="2.25" stroke-linecap="round" stroke-linejoin="round">${icon.nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('')}</svg>`;
  return `<!doctype html><meta charset="utf-8"><title>ink icons</title>
<body style="margin:0;padding:16px;background:#13101b;color:#f4f2ed;font:12px/1.3 ui-monospace,monospace">
<div style="display:grid;grid-template-columns:repeat(8,96px);gap:10px">
${icons.map((icon) => `<div style="background:#201929;border:1px solid #59476c;border-radius:9px;padding:8px;display:flex;flex-direction:column;align-items:center;gap:8px">
<div style="display:flex;align-items:center;gap:10px;color:#c7ff4d">${draw(icon, 44)}${draw(icon, 20)}${draw(icon, 14)}</div>
<div style="display:flex;align-items:center;gap:10px;color:#b29aff">${draw(icon, 20, 'currentColor')}${draw(icon, 14, 'currentColor')}</div>
<span>${icon.name}</span></div>`).join('\n')}
</div>`;
}

function main() {
  const args = process.argv.slice(2);
  const sheetAt = args.indexOf('--sheet');
  const packageDir = args[0];
  if (!packageDir || sheetAt === 0) {
    console.error('usage: generate-icon-paths.mjs <lucide-react-package-dir> [name ...] [--sheet file.html]');
    process.exit(2);
  }
  const names = args.slice(1).filter((arg, i, all) => arg !== '--sheet' && all[i - 1] !== '--sheet');
  const icons = (names.length ? names : ICON_NAMES).map((name) => readIcon(packageDir, name));
  if (sheetAt !== -1) {
    fs.writeFileSync(args[sheetAt + 1], sheet(packageDir, icons));
    console.error(`wrote ${args[sheetAt + 1]} (${icons.length} icons)`);
    return;
  }
  process.stdout.write(tsModule(packageDir, icons));
}

if (import.meta.url === `file://${process.argv[1]}`) main();
