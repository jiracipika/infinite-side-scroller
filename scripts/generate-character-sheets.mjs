#!/usr/bin/env node
// Reads design/sheets/<id>.png strips and writes the base64-embedded generated
// module the sprite-sheet lane draws from. Run after replacing any sheet art:
//   node scripts/generate-character-sheets.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(fileURLToPath(import.meta.url), '..', '..');
const dir = path.join(root, 'design', 'sheets');
const out = path.join(root, 'src', 'game', 'rendering', 'character-sheets-data.ts');
const layouts = JSON.parse(readFileSync(path.join(dir, 'layouts.json'), 'utf8'));

const entries = [];
for (const f of readdirSync(dir).filter((f) => f.endsWith('.png')).sort()) {
  const id = f.replace(/\.png$/, '');
  const png = readFileSync(path.join(dir, f));
  const layout = layouts[id];
  if (!layout || png.readUInt32BE(16) !== layout.frameWidth * 6 || png.readUInt32BE(20) !== layout.frameHeight) {
    throw new Error(`Missing/mismatched layout for ${id}`);
  }
  const b64 = png.toString('base64');
  entries.push(`  ${JSON.stringify(id)}: 'data:image/png;base64,${b64}',`);
}
if (entries.length === 0) {
  console.error('no .png strips found in design/sheets/');
  process.exit(1);
}

const banner = `// GENERATED by scripts/generate-character-sheets.mjs — do not edit by hand.
// Source of truth: design/sheets/<id>.png. Regenerate after replacing art.
// Stem stays dot-free: the test alias loader only appends .ts to extensionless
// specifiers (path.extname must not see a fake extension).
// Six frames, order idle,run,air,dash,melee,tumble. Layouts keep the original
// body origin and accessory overhang; frame dimensions vary per character.
export interface CharacterSheetLayout {
  frameWidth: number;
  frameHeight: number;
  originX: number;
  originY: number;
  density: number;
  bodyWidth: number;
  bodyHeight: number;
  idleBounds: { left: number; top: number; right: number; bottom: number };
}
export const CHARACTER_SHEET_LAYOUTS: Record<string, CharacterSheetLayout> = ${JSON.stringify(layouts, null, 2)};
export const CHARACTER_SHEETS: Record<string, string> = {
${entries.join('\n')}
};
`;
writeFileSync(out, banner);
console.log('generated', path.relative(root, out), 'entries:', entries.length);
